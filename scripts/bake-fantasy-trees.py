#!/usr/bin/env python3
"""Bake the 4 Blender fantasy trees into a JS module for the game.

Reuses the GLB parser from scripts/bake-kenney.py (bk.bake merges one
model's primitives into indexed position/normal/color arrays;
material colours become vertex colours). The glTF exporter already
converted Blender Z-up to glTF Y-up, so a trunk built from z=0 up
arrives standing on game y=0.

Checks per model (fail the bake on violation):
- nothing buried deeper than 0.20 m (root flares are half-buried by
  design, everything else sits on the ground),
- the trunk ring touches y=0 (the model is grounded, not floating),
- no NaN coordinates, no degenerate (zero-area) triangles.

Usage: python3 bake-fantasy-trees.py
Writes: js/vendor/fantasy-trees.js
"""
import importlib.util
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
TREES = os.path.join(ROOT, 'vendor-src', 'trees')

spec = importlib.util.spec_from_file_location(
    'bake_kenney', os.path.join(HERE, 'bake-kenney.py'))
bk = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bk)

BARK_RGBS = [(0.350, 0.260, 0.190), (0.850, 0.820, 0.780)]


def check_model(name, b):
    pos, idx = b['pos'], b['index']
    ys = pos[1::3]
    min_y = min(ys)
    assert min_y >= -0.20, f'{name}: buried below -0.20 (min y {min_y})'
    # Trunk ring: bark-coloured verts must reach y=0 (grounded).
    col = b['col']
    trunk_min = min(
        (pos[i + 1] for i in range(0, len(pos), 3)
         if any(all(abs(col[i + k] - rgb[k]) < 0.02 for k in range(3)) for rgb in BARK_RGBS)),
        default=None)
    assert trunk_min is not None and trunk_min < 0.05, \
        f'{name}: trunk does not reach the ground (min bark y {trunk_min})'
    for v in pos + b['nor'] + b['col']:
        assert v == v and abs(v) != float('inf'), f'{name}: NaN/inf in geometry'
    degen = 0
    for i in range(0, len(idx), 3):
        a, c, d = idx[i], idx[i + 1], idx[i + 2]
        ax, ay, az = pos[a * 3:a * 3 + 3]
        bx, by, bz = pos[c * 3:c * 3 + 3]
        cx, cy, cz = pos[d * 3:d * 3 + 3]
        ux, uy, uz = bx - ax, by - ay, bz - az
        vx, vy, vz = cx - ax, cy - ay, cz - az
        area2 = (uy * vz - uz * vy) ** 2 + (uz * vx - ux * vz) ** 2 + (ux * vy - uy * vx) ** 2
        if area2 < 1e-12:
            degen += 1
    assert degen == 0, f'{name}: {degen} degenerate triangles'
    return min_y, trunk_min


def main():
    with open(os.path.join(TREES, 'models.json')) as f:
        meta = json.load(f)
    entries = []
    total = 0
    for m in meta:
        b = bk.bake(os.path.join(TREES, m['name'] + '.glb'))
        min_y, trunk_min = check_model(m['name'], b)
        print(f"{m['name']:8s} tris={b['tris']:5d} min_y={min_y:.3f} "
              f"trunk_min_y={trunk_min:.3f} bbox={b['bbox']['min']}..{b['bbox']['max']}")
        total += b['tris']
        entries.append(
            f"  {m['name']}: {{ pos: [{bk.fmt_nums(b['pos'])}], "
            f"nor: [{bk.fmt_nums(b['nor'])}], col: [{bk.fmt_nums(b['col'])}], "
            f"index: [{','.join(str(i) for i in b['index'])}] }}")
    lines = [
        '// Baked Blender fantasy trees (metres, origin at ground). Generated by',
        '// scripts/bake-fantasy-trees.py from vendor-src/trees/*.glb — do not edit by hand.',
        'export const FANTASY_TREES = {',
        ',\n'.join(entries),
        '};',
        '',
    ]
    out = os.path.join(ROOT, 'js', 'vendor', 'fantasy-trees.js')
    with open(out, 'w') as f:
        f.write('\n'.join(lines))
    print(f'wrote {out} ({os.path.getsize(out)//1024} KiB), {total} tris across models')


if __name__ == '__main__':
    main()
