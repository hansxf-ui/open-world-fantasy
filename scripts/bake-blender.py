#!/usr/bin/env python3
"""Bake a Blender-made GLB into a JS module for the game.

Reuses the GLB parser from scripts/bake-kenney.py (untextured models:
per-primitive material colors become vertex colors). Blender models
are built at real walker scale, so no rescaling happens here.

Also reports the door check: vertices carrying the door color must
sit on the +Z side (the game faces house fronts +Z, toward the plaza).

Usage: python3 bake-blender.py <input.glb> <output.js> <const-name>
Example: python3 bake-blender.py vendor-src/blender/sample-house.glb \\
           js/vendor/blender-house.js BLENDER_HOUSE
"""
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

spec = importlib.util.spec_from_file_location(
    'bake_kenney', os.path.join(HERE, 'bake-kenney.py'))
bk = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bk)

DOOR_RGB = (0.420, 0.259, 0.149)  # brown, as set in model-sample-house.py


def main():
    src, out, const = sys.argv[1], sys.argv[2], sys.argv[3]
    b = bk.bake(src)
    print(f'tris={b["tris"]} bbox min={b["bbox"]["min"]} max={b["bbox"]["max"]}')
    # Door-orientation check: door-colored verts must face +Z.
    dz = [b['pos'][i + 2] for i in range(0, len(b['pos']), 3)
          if all(abs(b['col'][i + k] - DOOR_RGB[k]) < 0.02 for k in range(3))]
    dy = [b['pos'][i + 1] for i in range(0, len(b['pos']), 3)
          if all(abs(b['col'][i + k] - DOOR_RGB[k]) < 0.02 for k in range(3))]
    if dz:
        print(f'door verts: {len(dz)} z={min(dz):.3f}..{max(dz):.3f} '
              f'y={min(dy):.3f}..{max(dy):.3f} '
              f'({"FRONT +Z OK" if min(dz) > 0 else "FRONT FLIPPED - fix placement rotation"})')
    else:
        print('door verts: NONE FOUND (check the door material color)')
    lines = [
        f'// Baked Blender model (walker scale, meters). Generated by',
        f'// scripts/bake-blender.py from {src} — do not edit by hand.',
        f'export const {const} = {{',
        f'  pos: [{bk.fmt_nums(b["pos"])}],',
        f'  nor: [{bk.fmt_nums(b["nor"])}],',
        f'  col: [{bk.fmt_nums(b["col"])}],',
        f'  index: [{",".join(str(i) for i in b["index"])}],',
        f'  min: {b["bbox"]["min"]}, max: {b["bbox"]["max"]},',
        '};',
        '',
    ]
    with open(out, 'w') as f:
        f.write('\n'.join(lines))
    print(f'wrote {out} ({os.path.getsize(out)//1024} KiB)')


if __name__ == '__main__':
    main()
